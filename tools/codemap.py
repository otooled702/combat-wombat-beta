#!/usr/bin/env python3
"""Write docs/CODEMAP.md: every source file, its size, and the functions in it.

Run after adding or moving code:   python3 tools/codemap.py
Use it to find where something lives before you open a file.
"""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def title(text):
    m = re.search(r'/\*\s*=+\s*\n\s*(.+?)\s*\n', text)
    if m: return m.group(1).strip()
    m = re.search(r'/\*\s*-{2,}\s*(.+?)\s*-*\s*\*/', text)
    return m.group(1).strip() if m else ''
out = ['# Code map', '', 'Generated by `tools/codemap.py`. One line per file, then the functions it defines (in order).', '',
       '`build.py` joins `src/css/*.css` and `src/js/*.js` in file-name order, so everything lives in one scope:',
       'any function in any JS file can call any other.', '']
out += ['## JavaScript (`src/js/`)', '']
for f in sorted(os.listdir(os.path.join(ROOT, 'src', 'js'))):
    t = open(os.path.join(ROOT, 'src', 'js', f), encoding='utf-8').read()
    fns = re.findall(r'^function (\w+)\(', t, flags=re.M)
    consts = re.findall(r'^var ([A-Z][A-Z0-9_]{2,})\s*=', t, flags=re.M)
    out.append('### %s  (%d lines, %d KB)' % (f, t.count('\n') + 1, len(t) // 1024))
    out.append(title(t) and '*%s*' % title(t) or '')
    if consts: out.append('Constants: `' + '`, `'.join(consts) + '`')
    out.append('Functions: ' + (', '.join('`%s`' % x for x in fns) if fns else '(none at top level)'))
    out.append('')
out += ['## CSS (`src/css/`)', '']
for f in sorted(os.listdir(os.path.join(ROOT, 'src', 'css'))):
    t = open(os.path.join(ROOT, 'src', 'css', f), encoding='utf-8').read()
    out.append('- `%s`: %d lines, %d KB. %s' % (f, t.count('\n') + 1, len(t) // 1024, title(t)))
out += ['', '## Data (`src/data/`)', '']
for f in sorted(os.listdir(os.path.join(ROOT, 'src', 'data'))):
    out.append('- `%s`: %d KB' % (f, os.path.getsize(os.path.join(ROOT, 'src', 'data', f)) // 1024))
os.makedirs(os.path.join(ROOT, 'docs'), exist_ok=True)
open(os.path.join(ROOT, 'docs', 'CODEMAP.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n'); print('wrote docs/CODEMAP.md')
